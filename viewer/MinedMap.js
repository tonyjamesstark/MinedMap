// bsearch-based array element check
function contains(array, elem) {
	let min = 0, max = array.length;

	while (min < max) {
		const i = min + Math.floor((max-min)/2);
		const cur = array[i];

		if (cur === elem)
			return true;
		else if (cur < elem)
			min = i + 1;
		else
			max = i;
	}

	return false;
}

const signKinds = {
	sign: {
		iconSize: [26, 28],
		popupAnchor: [0, -20],
	},
	wall_sign: {
		iconSize: [26, 18],
		popupAnchor: [0, -15],
	},
	hanging_sign: {
		iconSize: [28, 24],
		popupAnchor: [0, -18],
	},
	hanging_wall_sign: {
		iconSize: [28, 28],
		popupAnchor: [0, -20],
	},
}

const params = {};
const signIcons = {};
const markers = {};

let updateHash = () => {};

function coordKey(coords) {
	if (!coords)
		return null;

	return `${coords[0]},${coords[1]}`;
}

function getMarker(coords) {
	return markers[coordKey(coords)];
}

function signIcon(material, kind) {
	function createSignIcon(material, kind) {
		const {iconSize, popupAnchor} = signKinds[kind];

		return L.icon({
			iconUrl: `images/icon/${material}_${kind}.png`,
			iconSize,
			popupAnchor,
			shadowUrl: `images/icon/shadow_${kind}.png`,
			shadowSize: [iconSize[0]+8, iconSize[1]+8],
			className: 'overzoomed',
		});
	}


	let icons = signIcons[material] ??= {};
	return icons[kind] ??= createSignIcon(material, kind);
}

const MinedMapLayer = L.TileLayer.extend({
	initialize: function (mipmaps, layer, tile_extension, base) {
		L.TileLayer.prototype.initialize.call(this, '', {
			detectRetina: true,
			tileSize: 512,
			zoomReverse: true,
			minZoom: -(mipmaps.length-1),
			maxZoom: 0,
			attribution: 'Generated by <a href="https://github.com/neocturne/MinedMap">MinedMap</a>',
		});

		this.options.maxNativeZoom = this.options.maxZoom;
		this.options.maxZoom = undefined;

		this.mipmaps = mipmaps;
		this.layer = layer;
		this.ext = tile_extension;
		this.base = base;
	},

	createTile: function (coords, done) {
		const tile = L.TileLayer.prototype.createTile.call(this, coords, done);

		if (coords.z - this.options.zoomOffset >= 0)
			L.DomUtil.addClass(tile, 'overzoomed');

		return tile;
	},

	getTileUrl: function (coords) {
		let z = -coords.z + this.options.zoomOffset;
		if (z < 0)
			z = 0;

		const mipmap = this.mipmaps[z];

		if (coords.x < mipmap.bounds.minX || coords.x > mipmap.bounds.maxX ||
		    coords.y < mipmap.bounds.minZ || coords.y > mipmap.bounds.maxZ ||
		    !contains(mipmap.regions[coords.y] || [], coords.x))
			return L.Util.emptyImageUrl;


		return `${this.base}/${this.layer}/${z}/r.${coords.x}.${coords.y}.${this.ext}`;
	},
});


const CoordControl = L.Control.extend({
	initialize: function () {
		this.options.position = 'bottomleft';
	},

	onAdd: function (map) {
		this._container = L.DomUtil.create('div', 'leaflet-control-attribution');

		return this._container;
	},

	update: function (x, z) {
		if (!this._map) { return; }

		this._container.innerHTML = 'X: ' + x + '&nbsp;&nbsp;&nbsp;Z: ' + z;
	}
});


const parseHash = function () {
	const args = {};

	if (window.location.hash) {
		const parts = window.location.hash.substring(1).split('&');

		for (const part of parts) {
			const key_value = part.split('=');
			const key = key_value[0], value = key_value.slice(1).join('=');

			args[key] = value;
		}
	}

	return args;
}

function formatSignLine(line) {
	const el = document.createElement('span');
	el.style.whiteSpace = 'pre';

	for (const span of line) {
		const child = document.createElement('span');
		child.textContent = span.text;

		let color = span.color ?? '';
		if (color[0] !== '#')
			color = '#000000';

		if (span.bold)
			child.style.fontWeight = 'bold';
		if (span.italic)
			child.style.fontStyle = 'italic';

		child.style.textDecoration = '';
		if (span.underlined)
			child.style.textDecoration += ' underline';
		if (span.strikethrough)
			child.style.textDecoration += ' line-through';

		child.style.color = color;
		if (span.obfuscated) {
			child.style.backgroundColor = color;
			child.className = 'obfuscated';
		}

		el.appendChild(child);
	}
	return el;
}

function createSign(sign, back) {
	// standing signs
	function px(base) {
		const scale = 11;
		return (base*scale)+'px';
	}
	// hanging signs
	function pxh(base) {
		const scale = 16;
		return (base*scale)+'px';
	}

	const sizes = {
		sign: {
			width: px(24),
			height: px(12),
			paddingTop: px(0),
			paddingBottom: px(14),
		},
		wall_sign: {
			width: px(24),
			height: px(12),
			paddingTop: px(0),
			paddingBottom: px(0),
		},
		hanging_sign: {
			width: pxh(16),
			height: pxh(10),
			paddingTop: pxh(4),
			paddingBottom: pxh(0),
		},
		hanging_wall_sign: {
			width: pxh(16),
			height: pxh(10),
			paddingTop: pxh(6),
			paddingBottom: pxh(0),
		},
	};
	const size = sizes[sign.kind];

	const wrapper = document.createElement('div');
	wrapper.classList = 'sign-wrapper';

	const title = document.createElement('div');
	title.classList = 'sign-title'
	title.textContent = `Sign at ${sign.x}/${sign.y}/${sign.z}`;
	if (back)
		title.textContent += ' (back)';
	title.textContent += ':';

	wrapper.appendChild(title);

	const container = document.createElement('div');
	container.style.width = size.width;
	container.style.height = size.height;
	container.style.paddingTop = size.paddingTop;
	container.style.paddingBottom = size.paddingBottom;
	container.style.backgroundImage = `url(images/bg/${sign.material}_${sign.kind}.png)`;
	container.classList = 'sign-container overzoomed';

	const content = document.createElement('div');
	content.classList = 'sign-content';

	let text = [];
	if (!back && sign.front_text)
		text = sign.front_text;
	else if (back && sign.back_text)
		text = sign.back_text;

	for (const line of text) {
		content.appendChild(formatSignLine(line));
		content.appendChild(document.createElement('br'));
	}

	container.appendChild(content);
	wrapper.appendChild(container);

	return wrapper;
}

async function loadSigns(signLayer, base) {
	const response = await fetch(`${base}/entities.json`, {cache: 'no-store'});
	const res = await response.json();

	const groups = {};

	// Group signs by x,z coordinates
	for (const sign of res.signs) {
		const key = coordKey([sign.x, sign.z]);
		const group = groups[key] ??= [];
		group.push(sign);
	}

	for (const [key, group] of Object.entries(groups)) {
		const el = document.createElement('div');

		let material;
		let kind;

		// Sort from top to bottom
		group.sort((a, b) => b.y - a.y);

		for (const sign of group) {
			el.appendChild(createSign(sign, false));

			if (sign.back_text)
				el.appendChild(createSign(sign, true));

			material ??= sign.material;
			kind ??= sign.kind;
		}

		// Default material
		material ??= 'oak';

		const [x, z] = key.split(',').map((i) => +i);

		const popup = L.popup().setContent(el);

		popup.on('add', () => {
			params.marker = [x, z];
			updateHash();
		});
		popup.on('remove', () => {
			params.marker = null;
			updateHash();
		});

		const marker = L.marker([-z-0.5, x+0.5], {
			icon: signIcon(material, kind),
		}).addTo(signLayer).bindPopup(popup);

		markers[coordKey([x, z])] = marker;

		if (params.marker && x === params.marker[0] && z === params.marker[1])
			marker.openPopup();
	}
}

function createMarkerPopup(marker) {
	const el = document.createElement('div');
	for (const line of marker.text) {
		const b = document.createElement('b');
		b.textContent = line;
		el.appendChild(b);
		el.appendChild(document.createElement('br'));
	}
	el.appendChild(document.createTextNode(
		`${Math.floor(marker.x)} / ${Math.floor(marker.y)} / ${Math.floor(marker.z)}`));
	return el;
}

async function createRegionPopup(layer, x, z) {
	const name = `r.${x}.${z}`;
	const url = `${layer.downloads.path}/${name}.${layer.downloads.ext ?? 'zip'}`;

	const el = document.createElement('div');
	const title = document.createElement('b');
	title.textContent = `Region ${name}`;
	el.appendChild(title);
	el.appendChild(document.createElement('br'));
	el.appendChild(document.createTextNode(
		`X ${512*x} to ${512*x+511}, Z ${512*z} to ${512*z+511}`));
	el.appendChild(document.createElement('br'));

	const link = document.createElement('a');
	link.href = url;
	link.download = '';
	link.textContent = 'Download';
	el.appendChild(link);

	const response = await fetch(url, {method: 'HEAD'});
	const size = response.ok && response.headers.get('Content-Length');
	if (size)
		link.textContent += ` (${(size / 1048576).toFixed(1)} MB)`;

	return el;
}

window.createMap = function () {
	(async function () {
		// layers.json lists alternative data directories (e.g. cave slices or
		// other dimensions); without it, the single 'data' directory is used.
		let layerDefs = [{id: '', label: '', path: 'data'}];
		const layersResponse = await fetch('layers.json', {cache: 'no-store'});
		if (layersResponse.ok)
			layerDefs = await layersResponse.json();

		const layers = await Promise.all(layerDefs.map(async (def) => {
			const response = await fetch(`${def.path}/info.json`, {cache: 'no-store'});
			const info = await response.json();
			const tile_extension = info.tile_extension || 'png';
			return {
				...def,
				scale: def.scale ?? 1,
				info,
				features: info.features || {},
				markerSets: await Promise.all((def.markers ?? []).map(async (path) => {
					const response = await fetch(path, {cache: 'no-store'});
					return response.json();
				})),
				mapLayer: new MinedMapLayer(info.mipmaps, 'map', tile_extension, def.path),
				lightLayer: new MinedMapLayer(info.mipmaps, 'light', tile_extension, def.path),
			};
		}));
		const layerById = Object.fromEntries(layers.map((layer) => [layer.id, layer]));
		const {spawn} = layers[0].info;
		let active = layers[0];

		const updateParams = function () {
			const args = parseHash();

			params.zoom = parseInt(args['zoom']);
			params.x = parseFloat(args['x']);
			params.z = parseFloat(args['z']);
			params.light = parseInt(args['light']);
			params.signs = parseInt(args['signs'] ?? '1');
			params.marker = (args['marker'] ?? '').split(',').map((i) => +i);
			params.layer = layerById[args['layer']] ?? layers[0];

			if (isNaN(params.zoom))
				params.zoom = 0;
			if (isNaN(params.x))
				params.x = spawn.x / params.layer.scale;
			if (isNaN(params.z))
				params.z = spawn.z / params.layer.scale;
			if (!params.layer.features.signs || isNaN(params.marker[0]) || isNaN(params.marker[1]))
				params.marker = null;
		};

		updateParams();

		const layerBounds = function (layer) {
			const {bounds} = layer.info.mipmaps[0];
			return [
				[-512*(bounds.maxZ+1), 512*bounds.minX],
				[-512*bounds.minZ, 512*(bounds.maxX+1)],
			];
		};

		const map = L.map('map', {
			center: [-params.z, params.x],
			zoom: params.zoom,
			maxZoom: 5,
			crs: L.CRS.Simple,
		});

		const refocus = function() {
			map.getContainer().focus();
		};
		refocus();

		const overlayMaps = {};

		// Overlays are groups whose content follows the active layer
		const lightLayer = L.layerGroup();
		overlayMaps['Illumination'] = lightLayer;
		if (params.light)
			map.addLayer(lightLayer);

		const signLayer = L.layerGroup();
		if (layers.some((layer) => layer.features.signs)) {
			if (params.signs)
				map.addLayer(signLayer);

			overlayMaps['Signs'] = signLayer;
		}

		// One overlay per marker set label, filled from the active layer
		const markerRenderer = L.canvas();
		const markerOverlays = {};
		for (const layer of layers)
			for (const set of layer.markerSets)
				markerOverlays[set.label] ??= L.layerGroup().addTo(map);
		Object.assign(overlayMaps, markerOverlays);

		// Switches the active layer; the map view is left to the caller
		const activate = function (layer) {
			active = layer;
			map.setMinZoom(-(layer.info.mipmaps.length-1));
			map.setMaxBounds(layerBounds(layer));

			lightLayer.clearLayers();
			lightLayer.addLayer(layer.lightLayer);

			signLayer.clearLayers();
			for (const key of Object.keys(markers))
				delete markers[key];
			if (layer.features.signs)
				loadSigns(signLayer, layer.path);

			for (const group of Object.values(markerOverlays))
				group.clearLayers();
			for (const set of layer.markerSets) {
				for (const marker of set.markers) {
					L.circleMarker([-marker.z-0.5, marker.x+0.5], {
						renderer: markerRenderer,
						radius: 5,
						color: '#000',
						weight: 1,
						fillColor: '#ffcc00',
						fillOpacity: 0.9,
						bubblingMouseEvents: false,
					})
						.bindTooltip(() => {
							// Marker text is user input: never let Leaflet parse it as HTML
							const el = document.createElement('span');
							el.textContent = marker.text.join(': ');
							return el;
						})
						.bindPopup(() => createMarkerPopup(marker), {className: 'info-popup'})
						.addTo(markerOverlays[set.label]);
				}
			}
		};

		activate(params.layer);
		params.layer.mapLayer.addTo(map);

		const baseMaps = {};
		if (layers.length > 1)
			for (const layer of layers)
				baseMaps[layer.label] = layer.mapLayer;

		L.control.layers(baseMaps, overlayMaps).addTo(map);

		const coordControl = new CoordControl();
		coordControl.addTo(map);

		map.on('mousemove', function(e) {
			coordControl.update(Math.round(e.latlng.lng), Math.round(-e.latlng.lat));
		});

		const makeHash = function () {
			let ret = '#x='+params.x+'&z='+params.z;

			if (params.zoom != 0)
				ret += '&zoom='+params.zoom;

			if (active !== layers[0])
				ret += '&layer='+active.id;
			if (map.hasLayer(lightLayer))
				ret += '&light=1';
			if (active.features.signs && !map.hasLayer(signLayer))
				ret += '&signs=0';
			if (params.marker) {
				ret += `&marker=${params.marker[0]},${params.marker[1]}`;
			}

			return ret;
		};

		updateHash = function () {
			window.location.hash = makeHash();
		};

		const refreshHash = function (ev) {
			if (ev.type === 'layeradd' || ev.type === 'layerremove') {
				if (ev.layer !== lightLayer && ev.layer !== signLayer)
					return;
			}

			const center = map.getCenter();

			params.zoom = map.getZoom();
			params.x = Math.round(center.lng);
			params.z = Math.round(-center.lat);

			updateHash();
		}

		updateHash();

		map.on('moveend', refreshHash);
		map.on('zoomend', refreshHash);
		map.on('layeradd', refreshHash);
		map.on('layerremove', refreshHash);

		map.on('click', async function (ev) {
			const layer = active;
			if (!layer.downloads)
				return;

			const x = Math.floor(ev.latlng.lng / 512);
			const z = Math.floor(-ev.latlng.lat / 512);
			if (!contains(layer.info.mipmaps[0].regions[z] || [], x))
				return;

			const content = await createRegionPopup(layer, x, z);
			if (layer === active)
				L.popup({className: 'info-popup'}).setLatLng(ev.latlng).setContent(content).openOn(map);
		});

		map.on('baselayerchange', function (ev) {
			const layer = layers.find((layer) => layer.mapLayer === ev.layer);
			const ratio = active.scale / layer.scale;
			const center = map.getCenter();

			activate(layer);
			params.marker = null;
			map.setView([center.lat*ratio, center.lng*ratio], map.getZoom());
			refreshHash({type: 'baselayerchange'});
		});

		window.onhashchange = function () {
			// Keep keyboard focus on map when popups open or close
			refocus();

			if (window.location.hash === makeHash())
				return;

			const prevMarkerCoords = params.marker;

			updateParams();
			// Switching layers can move the map, which overwrites params
			const view = {center: [-params.z, params.x], zoom: params.zoom};

			if (params.light)
				map.addLayer(lightLayer);
			else
				map.removeLayer(lightLayer);

			if (params.layer !== active) {
				map.removeLayer(active.mapLayer);
				activate(params.layer);
				params.layer.mapLayer.addTo(map);
			}

			if (active.features.signs) {
				if (params.signs)
					map.addLayer(signLayer);
				else
					map.removeLayer(signLayer);

				if (coordKey(prevMarkerCoords) !== coordKey(params.marker))
					getMarker(params.marker)?.openPopup();
			}

			map.setView(view.center, view.zoom);

			updateHash();
		};

		window.onkeydown = function (event) {
			if (event.key === 'Escape') {
				map.closePopup();
				event.preventDefault();
			}
		};
	})();
}
