const parseHash = function () {
	const args = {};

	if (window.location.hash) {
		const parts = window.location.hash.substring(1).split('&');

		for (const part of parts) {
			const key_value = part.split('=');
			const key = key_value[0], value = key_value.slice(1).join('=');

			args[key] = value;
		}
	}

	return args;
}

function formatSignLine(line) {
	const el = document.createElement('span');
	el.style.whiteSpace = 'pre';

	for (const span of line) {
		const child = document.createElement('span');
		child.textContent = span.text;

		let color = span.color ?? '';
		if (color[0] !== '#')
			color = '#000000';

		if (span.bold)
			child.style.fontWeight = 'bold';
		if (span.italic)
			child.style.fontStyle = 'italic';

		child.style.textDecoration = '';
		if (span.underlined)
			child.style.textDecoration += ' underline';
		if (span.strikethrough)
			child.style.textDecoration += ' line-through';

		child.style.color = color;
		if (span.obfuscated) {
			child.style.backgroundColor = color;
			child.className = 'obfuscated';
		}

		el.appendChild(child);
	}
	return el;
}

function createSign(sign, back) {
	// standing signs
	function px(base) {
		const scale = 11;
		return (base*scale)+'px';
	}
	// hanging signs
	function pxh(base) {
		const scale = 16;
		return (base*scale)+'px';
	}

	const sizes = {
		sign: {
			width: px(24),
			height: px(12),
			paddingTop: px(0),
			paddingBottom: px(14),
		},
		wall_sign: {
			width: px(24),
			height: px(12),
			paddingTop: px(0),
			paddingBottom: px(0),
		},
		hanging_sign: {
			width: pxh(16),
			height: pxh(10),
			paddingTop: pxh(4),
			paddingBottom: pxh(0),
		},
		hanging_wall_sign: {
			width: pxh(16),
			height: pxh(10),
			paddingTop: pxh(6),
			paddingBottom: pxh(0),
		},
	};
	const size = sizes[sign.kind];

	const wrapper = document.createElement('div');
	wrapper.classList = 'sign-wrapper';

	const title = document.createElement('div');
	title.classList = 'sign-title'
	title.textContent = `Sign at ${sign.x}/${sign.y}/${sign.z}`;
	if (back)
		title.textContent += ' (back)';
	title.textContent += ':';

	wrapper.appendChild(title);

	const container = document.createElement('div');
	container.style.width = size.width;
	container.style.height = size.height;
	container.style.paddingTop = size.paddingTop;
	container.style.paddingBottom = size.paddingBottom;
	container.style.backgroundImage = `url(images/bg/${sign.material}_${sign.kind}.png)`;
	container.classList = 'sign-container overzoomed';

	const content = document.createElement('div');
	content.classList = 'sign-content';

	let text = [];
	if (!back && sign.front_text)
		text = sign.front_text;
	else if (back && sign.back_text)
		text = sign.back_text;

	for (const line of text) {
		content.appendChild(formatSignLine(line));
		content.appendChild(document.createElement('br'));
	}

	container.appendChild(content);
	wrapper.appendChild(container);

	return wrapper;
}

async function loadSigns(signLayer, base) {
	const response = await fetch(`${base}/entities.json`, {cache: 'no-store'});
	const res = await response.json();

	const groups = {};

	// Group signs by x,z coordinates
	for (const sign of res.signs) {
		const key = coordKey([sign.x, sign.z]);
		const group = groups[key] ??= [];
		group.push(sign);
	}

	for (const [key, group] of Object.entries(groups)) {
		const el = document.createElement('div');

		let material;
		let kind;

		// Sort from top to bottom
		group.sort((a, b) => b.y - a.y);

		for (const sign of group) {
			el.appendChild(createSign(sign, false));

			if (sign.back_text)
				el.appendChild(createSign(sign, true));

			material ??= sign.material;
			kind ??= sign.kind;
		}

		// Default material
		material ??= 'oak';

		const [x, z] = key.split(',').map((i) => +i);

		const popup = L.popup().setContent(el);

		popup.on('add', () => {
			params.marker = [x, z];
			updateHash();
		});
		popup.on('remove', () => {
			params.marker = null;
			updateHash();
		});

		const marker = L.marker([-z-0.5, x+0.5], {
			icon: signIcon(material, kind),
		}).addTo(signLayer).bindPopup(popup);

		markers[coordKey([x, z])] = marker;

		if (params.marker && x === params.marker[0] && z === params.marker[1])
			marker.openPopup();
	}
}

function createMarkerPopup(marker) {
	const el = document.createElement('div');
	for (const line of marker.text) {
		const b = document.createElement('b');
		b.textContent = line;
		el.appendChild(b);
		el.appendChild(document.createElement('br'));
	}
	el.appendChild(document.createTextNode(
		`${Math.floor(marker.x)} / ${Math.floor(marker.y)} / ${Math.floor(marker.z)}`));
	return el;
}

async function createRegionPopup(layer, x, z, selection) {
	const name = `r.${x}.${z}`;
	const {downloads} = layer;
	const ext = downloads.ext ?? 'zip';
	const variants = downloads.variants ?? [{label: 'Download', path: downloads.path}];

	const el = document.createElement('div');
	const title = document.createElement('b');
	title.textContent = `Region ${name}`;
	el.appendChild(title);
	el.appendChild(document.createElement('br'));
	el.appendChild(document.createTextNode(
		`X ${512*x} to ${512*x+511}, Z ${512*z} to ${512*z+511}`));

	// A variant may leave regions out (e.g. one that keeps only lived-in chunks)
	const sizes = await Promise.all(variants.map(async (variant) => {
		const response = await fetch(`${variant.path}/${name}.${ext}`, {method: 'HEAD'});
		return response.ok ? +(response.headers.get('Content-Length') ?? 0) : null;
	}));
	variants.forEach((variant, i) => {
		el.appendChild(document.createElement('br'));
		if (sizes[i] === null) {
			el.appendChild(document.createTextNode(`${variant.label}: not available`));
			return;
		}
		const link = document.createElement('a');
		link.href = `${variant.path}/${name}.${ext}`;
		link.download = '';
		link.textContent = variant.label;
		if (sizes[i])
			link.textContent += ` (${(sizes[i] / 1048576).toFixed(1)} MB)`;
		el.appendChild(link);
	});

	if (selection && sizes[0] !== null) {
		const toggle = document.createElement('button');
		toggle.type = 'button';
		toggle.className = 'link-button';
		const label = () => {
			toggle.textContent = selection.has(x, z) ? 'Remove from selection' : 'Add to selection';
		};
		label();
		toggle.onclick = async () => {
			await selection.toggle(layer, [[x, z]]);
			label();
		};
		el.appendChild(document.createElement('br'));
		el.appendChild(toggle);
	}

	if (downloads.help) {
		const help = document.createElement('a');
		help.href = downloads.help;
		help.target = '_blank';
		help.textContent = 'How to use';
		el.appendChild(document.createElement('br'));
		el.appendChild(help);
	}

	return el;
}

// Entries of a zip without ZIP64, with their compressed data as views into buf
function readZip(buf) {
	const v = new DataView(buf);
	let eocd = -1;
	for (let i = buf.byteLength - 22; i >= Math.max(0, buf.byteLength - 65557); i--) {
		if (v.getUint32(i, true) === 0x06054b50) {
			eocd = i;
			break;
		}
	}
	if (eocd < 0)
		throw new Error('not a zip file');

	const decoder = new TextDecoder();
	const entries = [];
	let p = v.getUint32(eocd + 16, true);
	for (let n = v.getUint16(eocd + 10, true); n > 0; n--) {
		if (v.getUint32(p, true) !== 0x02014b50)
			throw new Error('bad zip central directory');
		const nameLen = v.getUint16(p + 28, true);
		const csize = v.getUint32(p + 20, true);
		const offset = v.getUint32(p + 42, true);
		if (csize === 0xffffffff || offset === 0xffffffff)
			throw new Error('ZIP64 is not supported');
		const dataStart = offset + 30 + v.getUint16(offset + 26, true) + v.getUint16(offset + 28, true);
		entries.push({
			name: decoder.decode(new Uint8Array(buf, p + 46, nameLen)),
			madeBy: v.getUint16(p + 4, true),
			flags: v.getUint16(p + 8, true),
			method: v.getUint16(p + 10, true),
			time: v.getUint16(p + 12, true),
			date: v.getUint16(p + 14, true),
			crc: v.getUint32(p + 16, true),
			csize,
			usize: v.getUint32(p + 24, true),
			extAttr: v.getUint32(p + 38, true),
			data: new Uint8Array(buf, dataStart, csize),
		});
		p += 46 + nameLen + v.getUint16(p + 30, true) + v.getUint16(p + 32, true);
	}
	return entries;
}

// Copies entries into a new zip as they are: no recompression, so it is fast and CRCs hold
function writeZip(entries) {
	const encoder = new TextEncoder();
	const parts = [];
	const central = [];
	let offset = 0;
	let centralSize = 0;

	for (const e of entries) {
		const name = encoder.encode(e.name);
		// Drop the data descriptor bit (sizes are in the header now); names are UTF-8
		const flags = (e.flags & ~0x8) | 0x800;

		const local = new DataView(new ArrayBuffer(30));
		local.setUint32(0, 0x04034b50, true);
		local.setUint16(4, 20, true);
		local.setUint16(6, flags, true);
		local.setUint16(8, e.method, true);
		local.setUint16(10, e.time, true);
		local.setUint16(12, e.date, true);
		local.setUint32(14, e.crc, true);
		local.setUint32(18, e.csize, true);
		local.setUint32(22, e.usize, true);
		local.setUint16(26, name.length, true);
		parts.push(local, name, e.data);

		const dir = new DataView(new ArrayBuffer(46));
		dir.setUint32(0, 0x02014b50, true);
		dir.setUint16(4, e.madeBy, true);
		dir.setUint16(6, 20, true);
		dir.setUint16(8, flags, true);
		dir.setUint16(10, e.method, true);
		dir.setUint16(12, e.time, true);
		dir.setUint16(14, e.date, true);
		dir.setUint32(16, e.crc, true);
		dir.setUint32(20, e.csize, true);
		dir.setUint32(24, e.usize, true);
		dir.setUint16(28, name.length, true);
		dir.setUint32(38, e.extAttr, true);
		dir.setUint32(42, offset, true);
		central.push(dir, name);

		offset += 30 + name.length + e.csize;
		centralSize += 46 + name.length;
	}
	if (entries.length > 0xffff || offset + centralSize > 0xffffffff)
		throw new Error('selection too large for one zip');

	const end = new DataView(new ArrayBuffer(22));
	end.setUint32(0, 0x06054b50, true);
	end.setUint16(8, entries.length, true);
	end.setUint16(10, entries.length, true);
	end.setUint32(12, centralSize, true);
	end.setUint32(16, offset, true);

	return new Blob([...parts, ...central, end], {type: 'application/zip'});
}

// Region zips each hold one world folder; merge them under one root folder. The first zip
// wins for shared files (level.dat and its spawn, data/, datapacks/).
function mergeRegionZips(buffers, root) {
	const seen = new Set();
	const entries = [];
	for (const buf of buffers) {
		for (const entry of readZip(buf)) {
			const slash = entry.name.indexOf('/');
			const name = root + (slash < 0 ? '/' + entry.name : entry.name.slice(slash));
			if (seen.has(name))
				continue;
			seen.add(name);
			entries.push({...entry, name});
		}
	}
	return writeZip(entries);
}

// Browsers hold the whole selection in memory while the zip is assembled
const SELECTION_MAX_BYTES = 1024 * 1048576;
const SELECTION_MAX_DRAG = 256;

const formatMB = (bytes) => `${(bytes / 1048576).toFixed(1)} MB`;

const SelectionControl = L.Control.extend({
	initialize: function (selection) {
		this.selection = selection;
		this.options.position = 'topleft';
	},

	onAdd: function () {
		const el = L.DomUtil.create('div', 'leaflet-bar selection-control');
		L.DomEvent.disableClickPropagation(el);
		L.DomEvent.disableScrollPropagation(el);

		this.summary = L.DomUtil.create('div', 'selection-summary', el);
		this.status = L.DomUtil.create('div', 'selection-status', el);

		const buttons = L.DomUtil.create('div', '', el);
		this.download = L.DomUtil.create('button', '', buttons);
		this.download.type = 'button';
		this.download.textContent = 'Download as one world';
		this.download.onclick = () => this.selection.download();
		this.clear = L.DomUtil.create('button', '', buttons);
		this.clear.type = 'button';
		this.clear.textContent = 'Clear';
		this.clear.onclick = () => this.selection.clear();

		this.update();
		return el;
	},

	update: function (status) {
		if (!this.summary)
			return;
		const {count, bytes, busy} = this.selection;
		this.summary.textContent = count
			? `${count} region${count === 1 ? '' : 's'} selected, ${formatMB(bytes)}`
			: 'Select regions: shift-click or shift-drag, or "Add to selection" in a region popup';
		if (status !== undefined)
			this.status.textContent = status;
		this.download.disabled = busy || !count;
		this.clear.disabled = busy || !count;
	},
});

function createSelection(map) {
	const regions = new Map();
	const group = L.layerGroup().addTo(map);
	let path = null;
	let ext = 'zip';
	let control = null;

	const key = (x, z) => `${x},${z}`;
	const bounds = (x, z) => [[-512*(z+1), 512*x], [-512*z, 512*(x+1)]];
	const sizeOf = async (x, z) => {
		const response = await fetch(`${path}/r.${x}.${z}.${ext}`, {method: 'HEAD'});
		return response.ok ? +(response.headers.get('Content-Length') ?? 0) : null;
	};

	const selection = {
		busy: false,
		get count() { return regions.size; },
		get bytes() {
			let total = 0;
			for (const region of regions.values())
				total += region.size;
			return total;
		},

		has: (x, z) => regions.has(key(x, z)),

		// Follows the active layer: layers that share a download folder (cave slices of
		// the overworld) keep the selection, any other clears it
		follow(layer) {
			const variant = layer.downloads?.variants?.[0] ?? layer.downloads;
			const next = variant?.path ?? null;
			if (next !== path)
				selection.clear();
			path = next;
			ext = layer.downloads?.ext ?? 'zip';
			selection.layer = layer;
			if (!path && control) {
				control.remove();
				control = null;
			} else if (path && !control) {
				control = new SelectionControl(selection).addTo(map);
			}
		},

		// Toggles one region, or adds every available region in a dragged range
		async toggle(layer, cells) {
			if (!path || selection.busy)
				return;
			const rendered = layer.info.mipmaps[0].regions;
			cells = cells.filter(([x, z]) => contains(rendered[z] || [], x));
			if (cells.length === 1 && selection.has(...cells[0])) {
				const [x, z] = cells[0];
				group.removeLayer(regions.get(key(x, z)).rect);
				regions.delete(key(x, z));
				control?.update('');
				return;
			}
			cells = cells.filter(([x, z]) => !selection.has(x, z));
			if (cells.length > SELECTION_MAX_DRAG) {
				control?.update(`That covers ${cells.length} regions; select at most ${SELECTION_MAX_DRAG} at a time.`);
				return;
			}
			const sizes = await Promise.all(cells.map(([x, z]) => sizeOf(x, z)));
			let total = selection.bytes;
			let skipped = 0;
			cells.forEach(([x, z], i) => {
				if (sizes[i] === null || selection.has(x, z))
					return;
				if (total + sizes[i] > SELECTION_MAX_BYTES) {
					skipped++;
					return;
				}
				total += sizes[i];
				const rect = L.rectangle(bounds(x, z), {
					color: '#ffcc00', weight: 2, fillOpacity: 0.15, interactive: false,
				}).addTo(group);
				regions.set(key(x, z), {x, z, size: sizes[i], rect});
			});
			control?.update(skipped
				? `${skipped} region${skipped === 1 ? '' : 's'} left out: one download holds at most ${formatMB(SELECTION_MAX_BYTES)}.`
				: '');
		},

		clear() {
			regions.clear();
			group.clearLayers();
			control?.update('');
		},

		async download() {
			if (!regions.size || selection.busy)
				return;
			selection.busy = true;
			try {
				// Spawn in the region nearest the middle of the selection
				const list = [...regions.values()];
				const cx = list.reduce((s, r) => s + r.x, 0) / list.length;
				const cz = list.reduce((s, r) => s + r.z, 0) / list.length;
				list.sort((a, b) => ((a.x-cx)**2 + (a.z-cz)**2) - ((b.x-cx)**2 + (b.z-cz)**2));

				const buffers = [];
				for (const [i, region] of list.entries()) {
					control?.update(`Fetching region ${i+1} of ${list.length}...`);
					const response = await fetch(`${path}/r.${region.x}.${region.z}.${ext}`);
					if (!response.ok)
						throw new Error(`r.${region.x}.${region.z}: HTTP ${response.status}`);
					buffers.push(await response.arrayBuffer());
				}

				control?.update('Building the zip...');
				const first = readZip(buffers[0])[0].name;
				const root = first.slice(0, first.indexOf('/')).replace(/-r\.-?\d+\.-?\d+$/, '') +
					`-${list.length}-regions`;
				const url = URL.createObjectURL(mergeRegionZips(buffers, root));
				const link = document.createElement('a');
				link.href = url;
				link.download = `${root}.zip`;
				document.body.appendChild(link);
				link.click();
				link.remove();
				setTimeout(() => URL.revokeObjectURL(url), 60000);
				control?.update(`Saved ${root}.zip`);
			} catch (e) {
				control?.update(`Download failed: ${e.message}`);
			} finally {
				selection.busy = false;
				control?.update();
			}
		},
	};

	// Shift-drag selects a range of regions (in place of Leaflet's shift-drag zoom)
	let start = null;
	let box = null;
	const cell = (latlng) => [Math.floor(latlng.lng / 512), Math.floor(-latlng.lat / 512)];
	// Capture phase: Leaflet's own drag handler would otherwise start panning first
	map.getContainer().addEventListener('mousedown', (ev) => {
		if (path && ev.shiftKey && ev.button === 0)
			map.dragging.disable();
	}, true);
	map.on('mousedown', (ev) => {
		if (!path || !ev.originalEvent.shiftKey)
			return;
		start = ev.latlng;
	});
	map.on('mousemove', (ev) => {
		if (!start)
			return;
		const b = L.latLngBounds(start, ev.latlng);
		if (box)
			box.setBounds(b);
		else
			box = L.rectangle(b, {color: '#ffcc00', weight: 1, dashArray: '4', fill: false, interactive: false}).addTo(map);
	});
	document.addEventListener('mouseup', () => map.dragging.enable());
	map.on('mouseup', (ev) => {
		if (!start)
			return;
		const [x0, z0] = cell(start), [x1, z1] = cell(ev.latlng);
		start = null;
		box?.remove();
		box = null;
		const cells = [];
		for (let z = Math.min(z0, z1); z <= Math.max(z0, z1); z++)
			for (let x = Math.min(x0, x1); x <= Math.max(x0, x1); x++)
				cells.push([x, z]);
		if (cells.length <= SELECTION_MAX_DRAG * 4)
			selection.toggle(selection.layer, cells);
		else
			control?.update(`That covers ${cells.length} regions; select at most ${SELECTION_MAX_DRAG} at a time.`);
	});

	return selection;
}

const LinksControl = L.Control.extend({
	initialize: function (links, options) {
		this.links = links;
		L.setOptions(this, options);
	},

	onAdd: function () {
		const el = L.DomUtil.create('div', 'leaflet-control-attribution links-control');
		this.links.forEach((entry, i) => {
			if (i)
				el.appendChild(document.createTextNode(' · '));
			const link = document.createElement('a');
			link.href = entry.href;
			link.target = '_blank';
			link.textContent = entry.label;
			el.appendChild(link);
		});
		return el;
	},
});

window.createMap = function () {
	(async function () {
		// layers.json lists alternative data directories (e.g. cave slices or
		// other dimensions), either as an array or as {layers, links}; without
		// it, the single 'data' directory is used.
		let layerDefs = [{id: '', label: '', path: 'data'}];
		let links = [];
		const layersResponse = await fetch('layers.json', {cache: 'no-store'});
		if (layersResponse.ok) {
			const config = await layersResponse.json();
			layerDefs = Array.isArray(config) ? config : config.layers;
			links = Array.isArray(config) ? [] : config.links ?? [];
		}

		const layers = await Promise.all(layerDefs.map(async (def) => {
			const response = await fetch(`${def.path}/info.json`, {cache: 'no-store'});
			const info = await response.json();
			const tile_extension = info.tile_extension || 'png';
			return {
				...def,
				scale: def.scale ?? 1,
				info,
				features: info.features || {},
				markerSets: await Promise.all((def.markers ?? []).map(async (path) => {
					const response = await fetch(path, {cache: 'no-store'});
					return response.json();
				})),
				mapLayer: new MinedMapLayer(info.mipmaps, 'map', tile_extension, def.path),
				lightLayer: new MinedMapLayer(info.mipmaps, 'light', tile_extension, def.path),
			};
		}));
		const layerById = Object.fromEntries(layers.map((layer) => [layer.id, layer]));
		const {spawn} = layers[0].info;
		let active = layers[0];

		const updateParams = function () {
			const args = parseHash();

			params.zoom = parseInt(args['zoom']);
			params.x = parseFloat(args['x']);
			params.z = parseFloat(args['z']);
			params.light = parseInt(args['light']);
			params.signs = parseInt(args['signs'] ?? '1');
			params.marker = (args['marker'] ?? '').split(',').map((i) => +i);
			params.layer = layerById[args['layer']] ?? layers[0];

			if (isNaN(params.zoom))
				params.zoom = 0;
			if (isNaN(params.x))
				params.x = spawn.x / params.layer.scale;
			if (isNaN(params.z))
				params.z = spawn.z / params.layer.scale;
			if (!params.layer.features.signs || isNaN(params.marker[0]) || isNaN(params.marker[1]))
				params.marker = null;
		};

		updateParams();

		const layerBounds = function (layer) {
			const {bounds} = layer.info.mipmaps[0];
			return [
				[-512*(bounds.maxZ+1), 512*bounds.minX],
				[-512*bounds.minZ, 512*(bounds.maxX+1)],
			];
		};

		const map = L.map('map', {
			center: [-params.z, params.x],
			zoom: params.zoom,
			// Layers add their min zoom only later; without this a negative hash zoom clamps to 0
			minZoom: -(params.layer.info.mipmaps.length-1),
			maxZoom: 5,
			crs: L.CRS.Simple,
			boxZoom: false,
		});

		const selection = createSelection(map);

		const refocus = function() {
			map.getContainer().focus();
		};
		refocus();

		const overlayMaps = {};

		// Overlays are groups whose content follows the active layer
		const lightLayer = L.layerGroup();
		overlayMaps['Illumination'] = lightLayer;
		if (params.light)
			map.addLayer(lightLayer);

		const signLayer = L.layerGroup();
		if (layers.some((layer) => layer.features.signs)) {
			if (params.signs)
				map.addLayer(signLayer);

			overlayMaps['Signs'] = signLayer;
		}

		// One overlay per marker set label, filled from the active layer
		const markerRenderer = L.canvas();
		const markerOverlays = {};
		for (const layer of layers)
			for (const set of layer.markerSets)
				markerOverlays[set.label] ??= L.layerGroup().addTo(map);
		Object.assign(overlayMaps, markerOverlays);

		// Switches the active layer; the map view is left to the caller
		const activate = function (layer) {
			active = layer;
			selection.follow(layer);
			map.setMinZoom(-(layer.info.mipmaps.length-1));
			map.setMaxBounds(layerBounds(layer));

			lightLayer.clearLayers();
			lightLayer.addLayer(layer.lightLayer);

			signLayer.clearLayers();
			for (const key of Object.keys(markers))
				delete markers[key];
			if (layer.features.signs)
				loadSigns(signLayer, layer.path);

			for (const group of Object.values(markerOverlays))
				group.clearLayers();
			for (const set of layer.markerSets) {
				for (const marker of set.markers) {
					L.circleMarker([-marker.z-0.5, marker.x+0.5], {
						renderer: markerRenderer,
						radius: 5,
						color: '#000',
						weight: 1,
						fillColor: '#ffcc00',
						fillOpacity: 0.9,
						bubblingMouseEvents: false,
					})
						.bindTooltip(() => {
							// Marker text is user input: never let Leaflet parse it as HTML
							const el = document.createElement('span');
							el.textContent = marker.text.join(': ');
							return el;
						})
						.bindPopup(() => createMarkerPopup(marker), {className: 'info-popup'})
						.addTo(markerOverlays[set.label]);
				}
			}
		};

		activate(params.layer);
		params.layer.mapLayer.addTo(map);

		const baseMaps = {};
		if (layers.length > 1)
			for (const layer of layers)
				baseMaps[layer.label] = layer.mapLayer;

		const layersControl = L.control.layers(baseMaps, overlayMaps);
		// Leaflet greys out layers with fewer zoom levels when zoomed out past them;
		// switching clamps the zoom instead (activate sets the new min zoom)
		layersControl._checkDisabledLayers = () => {};
		layersControl.addTo(map);

		const coordControl = new CoordControl();
		coordControl.addTo(map);

		if (links.length)
			new LinksControl(links, {position: 'bottomleft'}).addTo(map);

		map.on('mousemove', function(e) {
			coordControl.update(Math.round(e.latlng.lng), Math.round(-e.latlng.lat));
		});

		const makeHash = function () {
			let ret = '#x='+params.x+'&z='+params.z;

			if (params.zoom != 0)
				ret += '&zoom='+params.zoom;

			if (active !== layers[0])
				ret += '&layer='+active.id;
			if (map.hasLayer(lightLayer))
				ret += '&light=1';
			if (active.features.signs && !map.hasLayer(signLayer))
				ret += '&signs=0';
			if (params.marker) {
				ret += `&marker=${params.marker[0]},${params.marker[1]}`;
			}

			return ret;
		};

		updateHash = function () {
			window.location.hash = makeHash();
		};

		const refreshHash = function (ev) {
			if (ev.type === 'layeradd' || ev.type === 'layerremove') {
				if (ev.layer !== lightLayer && ev.layer !== signLayer)
					return;
			}

			const center = map.getCenter();

			params.zoom = map.getZoom();
			params.x = Math.round(center.lng);
			params.z = Math.round(-center.lat);

			updateHash();
		}

		updateHash();

		map.on('moveend', refreshHash);
		map.on('zoomend', refreshHash);
		map.on('layeradd', refreshHash);
		map.on('layerremove', refreshHash);

		map.on('click', async function (ev) {
			const layer = active;
			if (!layer.downloads || ev.originalEvent.shiftKey)
				return;

			const x = Math.floor(ev.latlng.lng / 512);
			const z = Math.floor(-ev.latlng.lat / 512);
			if (!contains(layer.info.mipmaps[0].regions[z] || [], x))
				return;

			const content = await createRegionPopup(layer, x, z, selection);
			if (layer === active)
				L.popup({className: 'info-popup'}).setLatLng(ev.latlng).setContent(content).openOn(map);
		});

		map.on('baselayerchange', function (ev) {
			const layer = layers.find((layer) => layer.mapLayer === ev.layer);
			const ratio = active.scale / layer.scale;
			const center = map.getCenter();

			activate(layer);
			params.marker = null;
			map.setView([center.lat*ratio, center.lng*ratio], map.getZoom());
			refreshHash({type: 'baselayerchange'});
		});

		window.onhashchange = function () {
			// Keep keyboard focus on map when popups open or close
			refocus();

			if (window.location.hash === makeHash())
				return;

			const prevMarkerCoords = params.marker;

			updateParams();
			// Switching layers can move the map, which overwrites params
			const view = {center: [-params.z, params.x], zoom: params.zoom};

			if (params.light)
				map.addLayer(lightLayer);
			else
				map.removeLayer(lightLayer);

			if (params.layer !== active) {
				map.removeLayer(active.mapLayer);
				activate(params.layer);
				params.layer.mapLayer.addTo(map);
			}

			if (active.features.signs) {
				if (params.signs)
					map.addLayer(signLayer);
				else
					map.removeLayer(signLayer);

				if (coordKey(prevMarkerCoords) !== coordKey(params.marker))
					getMarker(params.marker)?.openPopup();
			}

			map.setView(view.center, view.zoom);

			updateHash();
		};

		window.onkeydown = function (event) {
			if (event.key === 'Escape') {
				map.closePopup();
				event.preventDefault();
			}
		};
	})();
}
